/**
 * Eksik levha PNG'lerini images.weserv.nl üzerinden indirir (Commons rate limit bypass).
 */
const fs = require("fs");
const path = require("path");
const https = require("https");

const OUT = path.join(__dirname, "..", "assets", "isaretler");
const MAP = JSON.parse(fs.readFileSync(path.join(OUT, "kgm-map.json"), "utf8"));

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function get(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers: { "User-Agent": "EhliyetUstasi/1.0 (edu)" } }, (res) => {
        if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          const next = res.headers.location.startsWith("http")
            ? res.headers.location
            : new URL(res.headers.location, url).href;
          return get(next).then(resolve, reject);
        }
        const chunks = [];
        res.on("data", (c) => chunks.push(c));
        res.on("end", () => resolve({ status: res.statusCode, body: Buffer.concat(chunks) }));
      })
      .on("error", reject);
  });
}

function isPng(buf) {
  return buf.length > 500 && buf[0] === 0x89 && buf[1] === 0x50;
}

function weservUrl(fileName) {
  const commonsPath = encodeURIComponent("commons.wikimedia.org/wiki/Special:FilePath/" + fileName);
  return `https://images.weserv.nl/?url=${commonsPath}&w=320&output=png`;
}

async function buildMap() {
  const ids = fs
    .readdirSync(OUT)
    .filter((f) => f.endsWith(".png"))
    .map((f) => f.replace(".png", ""))
    .filter((id) => isPng(fs.readFileSync(path.join(OUT, `${id}.png`))))
    .sort();

  const lines = [
    "/** Wikimedia Commons (CC BY-SA). Generated by scripts/download-changed-isaretler.js */",
    'import type { ImageSourcePropType } from "react-native";',
    "",
    "export const ISARET_IMAGES: Record<string, ImageSourcePropType> = {",
    ...ids.map((id) => `  "${id}": require("../../assets/isaretler/${id}.png"),`),
    "};",
    "",
    'export const ISARET_IMAGE_ATTRIBUTION = "Levha görselleri: Wikimedia Commons (CC BY-SA) — Karayolları Genel Müdürlüğü standart levhaları.";',
    "",
  ];
  fs.writeFileSync(path.join(__dirname, "..", "src", "data", "isaretImageMap.ts"), lines.join("\n"));
  console.log("map", ids.length);
}

async function main() {
  const entries = Object.entries(MAP).filter(([k]) => !k.startsWith("_"));
  const ok = [];

  for (const [id, meta] of entries) {
    const dest = path.join(OUT, `${id}.png`);
    if (fs.existsSync(dest) && isPng(fs.readFileSync(dest))) {
      console.log("SKIP", id);
      ok.push(id);
      continue;
    }

    const url = weservUrl(meta.file);
    for (let a = 0; a < 3; a++) {
      try {
        const { status, body } = await get(url);
        if (status === 200 && isPng(body)) {
          fs.writeFileSync(dest, body);
          console.log("OK", id, meta.kgm, body.length);
          ok.push(id);
          break;
        }
        console.log("FAIL", id, status, body.length);
      } catch (e) {
        console.log("ERR", id, e.message);
      }
      await sleep(4000 * (a + 1));
    }
    await sleep(1500);
  }

  await buildMap();
  console.log("done", ok.length, "/", entries.length);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
