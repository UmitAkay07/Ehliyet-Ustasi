/**
 * KGM eşleştirmesine göre Wikimedia Commons PNG indirir.
 * Kaynak: assets/isaretler/kgm-map.json
 */
const fs = require("fs");
const path = require("path");
const https = require("https");

const OUT = path.join(__dirname, "..", "assets", "isaretler");
const MAP = JSON.parse(fs.readFileSync(path.join(OUT, "kgm-map.json"), "utf8"));

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function get(url, redirects = 0) {
  return new Promise((resolve, reject) => {
    if (redirects > 8) return reject(new Error("too many redirects"));
    https
      .get(url, { headers: { "User-Agent": "EhliyetUstasi/1.0 (educational offline)" } }, (res) => {
        if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          const next = res.headers.location.startsWith("http")
            ? res.headers.location
            : new URL(res.headers.location, url).href;
          return get(next, redirects + 1).then(resolve, reject);
        }
        const chunks = [];
        res.on("data", (c) => chunks.push(c));
        res.on("end", () => resolve({ status: res.statusCode, body: Buffer.concat(chunks) }));
      })
      .on("error", reject);
  });
}

function isPng(buf) {
  return buf.length > 800 && buf[0] === 0x89 && buf[1] === 0x50;
}

async function download(id, fileName, force = false) {
  const dest = path.join(OUT, `${id}.png`);
  if (!force && fs.existsSync(dest)) {
    const b = fs.readFileSync(dest);
    if (isPng(b)) {
      console.log("SKIP", id);
      return true;
    }
  }

  const pathUrl =
    "https://commons.wikimedia.org/wiki/Special:FilePath/" +
    encodeURIComponent(fileName) +
    "?width=320";

  for (let a = 0; a < 4; a++) {
    try {
      const { status, body } = await get(pathUrl);
      if (status === 429) {
        console.log("429", id);
        await sleep(25000 * (a + 1));
        continue;
      }
      if (status === 200 && isPng(body)) {
        fs.writeFileSync(dest, body);
        console.log("OK", id, MAP[id].kgm, body.length);
        return true;
      }
      if (status === 200 && body.toString("utf8", 0, 200).includes("<svg")) {
        console.log("GOTSVG", id);
        return false;
      }
      console.log("FAIL", id, status, body.length);
    } catch (e) {
      console.log("ERR", id, e.message);
    }
    await sleep(8000 * (a + 1));
  }
  return false;
}

async function buildMap(ids) {
  const lines = [
    "/** Wikimedia Commons (CC BY-SA). Generated by scripts/download-isaret-png.js */",
    'import type { ImageSourcePropType } from "react-native";',
    "",
    "export const ISARET_IMAGES: Record<string, ImageSourcePropType> = {",
  ];
  for (const id of ids.sort()) {
    lines.push(`  "${id}": require("../../assets/isaretler/${id}.png"),`);
  }
  lines.push("};");
  lines.push("");
  lines.push(
    'export const ISARET_IMAGE_ATTRIBUTION = "Levha görselleri: Wikimedia Commons (CC BY-SA) — Karayolları Genel Müdürlüğü standart levhaları.";'
  );
  fs.writeFileSync(path.join(__dirname, "..", "src", "data", "isaretImageMap.ts"), lines.join("\n"));
  console.log("Wrote map", ids.length);
}

async function main() {
  const forceIds = process.argv.includes("--force");
  const onlyArg = process.argv.find((a) => a.startsWith("--only="));
  const only = onlyArg ? onlyArg.slice(7).split(",") : null;

  for (const f of fs.readdirSync(OUT)) {
    if (!f.endsWith(".png")) continue;
    const b = fs.readFileSync(path.join(OUT, f));
    if (!isPng(b)) {
      fs.unlinkSync(path.join(OUT, f));
      console.log("removed bad", f);
    }
  }

  const entries = Object.entries(MAP).filter(([k]) => !k.startsWith("_"));
  const ok = [];
  for (const [id, meta] of entries) {
    if (only && !only.includes(id)) continue;
    const force = forceIds || only !== null;
    if (await download(id, meta.file, force)) ok.push(id);
    await sleep(5000);
  }
  await buildMap(ok);
  console.log("Done", ok.length, "/", entries.length);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
